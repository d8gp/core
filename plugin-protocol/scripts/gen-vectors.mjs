#!/usr/bin/env node
// Embeds the shared connection-contract vectors into commonTest, because a
// test on iOS cannot read files. Run after any change to the vectors:
//   node plugin-protocol/scripts/gen-vectors.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pluginsRoot = process.env.D8GP_PLUGINS_ROOT || join(homedir(), 'workspace', 'd8gp-plugins');
const vectorsDir = join(pluginsRoot, 'sdk-plugin', 'testing', 'vectors');
const outFile = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'commonTest',
  'kotlin',
  'com',
  'd8gp',
  'plugins',
  'protocol',
  'connections',
  'VectorsGenerated.kt',
);

// A JVM string constant holds at most 65535 bytes and one UTF-16 unit takes
// up to three, so chunks stay well below that.
const CHUNK_UNITS = 16000;

const files = readdirSync(vectorsDir).filter((name) => name.endsWith('.json')).sort();

const digest = createHash('sha256');
for (const name of files) {
  digest.update(name, 'utf8');
  digest.update(Buffer.from([0]));
  digest.update(readFileSync(join(vectorsDir, name)));
  digest.update(Buffer.from([0]));
}

// Built from code points so that this source holds no invisible character.
const invisible = new RegExp(`[\x7f-\x9f${String.fromCharCode(0x2028, 0x2029)}]`, 'g');
const escapeInvisible = (text) =>
  text.replace(invisible, (unit) => `\\u${unit.charCodeAt(0).toString(16).padStart(4, '0')}`);

const isHighSurrogate = (unit) => unit >= 0xd800 && unit <= 0xdbff;

function chunksOf(text) {
  const chunks = [];
  let start = 0;
  while (start < text.length) {
    let end = Math.min(start + CHUNK_UNITS, text.length);
    if (end < text.length && isHighSurrogate(text.charCodeAt(end - 1))) end -= 1;
    chunks.push(text.slice(start, end));
    start = end;
  }
  return chunks.length > 0 ? chunks : [''];
}

// Inside a Kotlin raw string a dollar sign starts a template and three quotes
// end the string. A quote is only dangerous in a run of three or as the last
// character, so exactly those are written as templates. The replacements are
// functions because a dollar sign in a replacement STRING is itself a pattern.
const DOLLAR_TEMPLATE = "${'$'}";
const QUOTE_TEMPLATE = "${'\"'}";

function rawString(chunk) {
  const body = chunk
    .replace(/\$/g, () => DOLLAR_TEMPLATE)
    .replace(/"{3,}/g, (run) => QUOTE_TEMPLATE.repeat(run.length))
    .replace(/"$/, () => QUOTE_TEMPLATE);
  return `"""${body}"""`;
}

const constantName = (file) => file.replace(/\.json$/, '').replace(/-/g, '_').toUpperCase();

const lines = [
  '// Generated by plugin-protocol/scripts/gen-vectors.mjs from',
  '// d8gp-plugins/sdk-plugin/testing/vectors. Do not edit by hand.',
  '// VectorsFreshnessTest fails when this file is older than the vectors.',
  'package com.d8gp.plugins.protocol.connections',
  '',
  'object VectorsGenerated {',
  `    const val INPUT_DIGEST = "${digest.digest('hex')}"`,
  '',
  '    val FILES: List<String> = listOf(',
  ...files.map((name) => `        "${name}",`),
  '    )',
];
for (const name of files) {
  const minified = escapeInvisible(JSON.stringify(JSON.parse(readFileSync(join(vectorsDir, name), 'utf8'))));
  lines.push('', `    val ${constantName(name)}: String by lazy {`, '        listOf(');
  for (const chunk of chunksOf(minified)) lines.push(`            ${rawString(chunk)},`);
  lines.push('        ).joinToString("")', '    }');
}
lines.push('}', '');

writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${files.length} vector files to ${outFile}`);
